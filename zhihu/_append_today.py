LOG = ROOT / "处理日志.org"
log_lines = []
for e in ENTRIES:
    target = ROOT / e["file"]
    text = target.read_text(encoding="utf-8").rstrip("\n")
    tagline = ":" + e["tags"].strip(":") + ":"
    parts = [
        "",
        f"* {e['title']}  {tagline}",
        "  :PROPERTIES:",
        f"  :链接:  {e['url']}",
        f"  :作者:  {e['author']}",
        f"  :原文:  [[file:原文/{e['archive']}][打开本地归档]]",
        f"  :抓取:  {TODAY}",
        "  :END:",
        "",
        f"- 本地原文：[[file:原文/{e['archive']}][打开本地归档]]",
        f"- 一句话概括：{e['summary']}",
        "【方法/论点要点】",
    ]
    parts += [f"- {p}" for p in e["points"]]
    parts.append("【原文摘录】")
    for q in e["quotes"]:
        parts += ["#+begin_quote", q, "#+end_quote"]
    parts += ["【我的想法】", e["thought"], ""]
    target.write_text(text + "\n" + "\n".join(parts) + "\n", encoding="utf-8")
    log_lines.append(f"[{TODAY}] ✅ {e['title']}  {tagline} → {e['file']}")

with LOG.open("a", encoding="utf-8") as f:
    for line in log_lines:
        f.write(line + "\n")

